"""Make and choose the fixed reference voice a VoxCPM2 (or Chatterbox) language
speaks in, voices/voxcpm/<lang>.wav: candidates generated by VoxCPM2 itself (so
synthetic speakers, Apache 2.0, no third-party voice), each cloned on a few
sentences and scored. Three steps, each in the environment that has its model
(GPU pod):

    # 1. candidates + clones, in VoxCPM2's venv
    /workspace/venv_voxcpm/bin/python tools/voice_refs.py gen --out /opt/refs --langs ko,tr
    # 2. optional: the same sentences through Chatterbox Multilingual (a venv with
    #    chatterbox-tts 0.1.7 installed --no-deps over torch 2.8), cloned from each candidate
    /opt/venv_chatterbox/bin/python tools/voice_refs.py chatterbox --out /opt/refs --langs ko,tr
    # 3. scores, in the stack's Python (faster-whisper): CER of every clip, pitch per clip
    python3 tools/voice_refs.py score --out /opt/refs

Per candidate: A and B are designed voices (VoxCPM2's "(description)text"
voice design: a calm adult woman, a calm adult man), C and D are random
speakers. A candidate is STABLE when every clone's median pitch stays within
25% of the reference's and on the same side of 165 Hz: the Lao lesson (a new
speaker, even a man turning into a woman, mid-phrase; docs/dev/lessons-learned.md
§5). `score` picks, per language, the stable candidate with the lowest mean
clone character error rate (Whisper large-v3). A person listens before it ships.
"""
